  check(!visible($("send-btn"))&&visible($("stop-btn")),"Stop replaces Send instead of sitting next to it");
  const stop=$("stop-btn").getBoundingClientRect();
  check(stop.height>=44&&stop.top>=0&&stop.bottom<=innerHeight&&Math.abs(stop.right-sendRight)<2,"Stop retains the same reachable action position");
  check($("composer").getBoundingClientRect().height<expandedHeight,"Reading mode returns space to the response");
